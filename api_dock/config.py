def _expand_remote_config(static: Dict[str, Any], store: Any, label: str) -> Dict[str, Any]:
    """Apply lookup rows to a shared remote config (see load_shared_remote_config).

    Args:
        static: The file as written (load_static_remote_config).
        store: The LookupStore.
        label: The file path (for messages).

    Returns:
        The expanded contents.

    Raises:
        ValueError: If a template is misplaced or a ``{{lookup.*}}`` value
            can't be filled.
    """
    from api_dock.lookups import (
        check_plain, expand_entries, fill_templates, generated_versions, LOOKUPS_KEY,
    )

    if not static:
        return static

    def check_generated(entry: Dict[str, Any]) -> None:
        entry[REMOTE_VERSION_KEY] = check_plain(entry.get(REMOTE_VERSION_KEY), "version")
        entry[GENERATED_FLAG] = True

    remotes = {}
    for name, entry in (static.get(REMOTE_CONFIGS_KEY) or {}).items():
        if not isinstance(entry, dict):
            remotes[name] = entry
            continue
        versions = generated_versions(entry.get(REMOTE_VERSIONS_KEY))
        entry_label = f"{label}: remote '{name}'"
        filled = dict(_fill_lookup_values(
            {k: v for k, v in entry.items() if versions is None or k != REMOTE_VERSIONS_KEY},
            entry_label, store.config_dir,
        ))
        if versions is not None:
            filled[REMOTE_VERSIONS_KEY] = [
                version if origin is not None else fill_templates(version, None, store)
                for version, origin in expand_entries(
                    versions, store, f"{entry_label} versions", check_generated
                )
            ]
            if not filled[REMOTE_VERSIONS_KEY]:
                continue
        remotes[name] = filled
    return {**static, REMOTE_CONFIGS_KEY: remotes, LOOKUPS_KEY: static.get(LOOKUPS_KEY) or {}}


